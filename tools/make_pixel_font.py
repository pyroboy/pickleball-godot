TOP_PAD = 1       # blank line above the caps
LINE_HEIGHT = 11
BASE = TOP_PAD + 7

def g(*rows):
    rows = list(rows)
    while len(rows) < ROWS: rows.append("." * len(rows[0]))
    return rows

def lower(*rows):   # x-height glyphs: two blank ascender rows on top
    w = len(rows[0])
    return g("." * w, "." * w, *rows)

