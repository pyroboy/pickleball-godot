def main() -> None:
    root = os.path.join(os.path.dirname(__file__), "..", "assets", "fonts")
    os.makedirs(root, exist_ok=True)
    cols = 16
    cell_w = 8
    cell_h = ROWS + 2
    items = list(GLYPHS.items())
    width = cols * cell_w
    height = ((len(items) + cols - 1) // cols) * cell_h
    height = 1 << (height - 1).bit_length()   # power of two
    img = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    lines = []
    for index, (ch, rows) in enumerate(items):
        w = len(rows[0])
        assert all(len(r) == w for r in rows), ch
        assert len(rows) == ROWS, ch
        x0 = (index % cols) * cell_w + 1
        y0 = (index // cols) * cell_h + 1
        for y, row in enumerate(rows):
            for x, bit in enumerate(row):
                if bit == "#": img.putpixel((x0 + x, y0 + y), (255, 255, 255, 255))
        lines.append(f"char id={ord(ch)} x={x0} y={y0} width={w} height={ROWS} xoffset=0 "
                     f"yoffset={TOP_PAD} xadvance={w + 1} page=0 chnl=15")
    img.save(os.path.join(root, "arjo_pixel.png"))
    header = [
        f'info face="Arjo Pixel" size={SIZE} bold=0 italic=0 charset="" unicode=1 stretchH=100 '
        f'smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0',
        f"common lineHeight={LINE_HEIGHT} base={BASE} scaleW={width} scaleH={height} pages=1 packed=0",
        'page id=0 file="arjo_pixel.png"',
        f"chars count={len(lines)}",
    ]
    with open(os.path.join(root, "arjo_pixel.fnt"), "w") as f:
        f.write("\n".join(header + lines) + "\n")
    print(f"{len(lines)} glyphs -> assets/fonts/arjo_pixel.fnt ({width}x{height})")

if __name__ == "__main__":
    main()
